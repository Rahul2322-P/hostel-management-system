package com.klef.soa.docker.controller;

import com.klef.soa.docker.dto.ErrorResponse;
import com.klef.soa.docker.dto.HostelRequest;
import com.klef.soa.docker.dto.HostelResponse;
import com.klef.soa.docker.service.HostelService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/hostels")
@Tag(name = "Hostel Management", description = "Operations for creating, retrieving, and deleting hostel records")
public class HostelController {

    private final HostelService hostelService;

    public HostelController(HostelService hostelService) {
        this.hostelService = hostelService;
    }

    @GetMapping
    @Operation(summary = "Get all hostels", description = "Fetches a list of all registered hostels in the system")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Successfully retrieved list of hostels")
    })
    public ResponseEntity<List<HostelResponse>> getAllHostels() {
        List<HostelResponse> hostels = hostelService.getAllHostels();
        return ResponseEntity.ok(hostels);
    }

    @GetMapping("/{id}")
    @Operation(summary = "Get hostel by ID", description = "Fetches detailed information for a single hostel using its primary key")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "200", description = "Hostel found successfully"),
            @ApiResponse(responseCode = "404", description = "Hostel not found with specified ID",
                    content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    })
    public ResponseEntity<HostelResponse> getHostelById(@PathVariable Long id) {
        HostelResponse hostel = hostelService.getHostelById(id);
        return ResponseEntity.ok(hostel);
    }

    @PostMapping
    @Operation(summary = "Create a new hostel", description = "Registers a new hostel record. The primary key ID is auto-generated by the database.")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "201", description = "Hostel created successfully with generated ID"),
            @ApiResponse(responseCode = "400", description = "Validation error in request body",
                    content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    })
    public ResponseEntity<HostelResponse> createHostel(@Valid @RequestBody HostelRequest request) {
        HostelResponse createdHostel = hostelService.createHostel(request);
        return new ResponseEntity<>(createdHostel, HttpStatus.CREATED);
    }

    @DeleteMapping("/{id}")
    @Operation(summary = "Delete hostel by ID", description = "Permanently removes the specified hostel from the database")
    @ApiResponses(value = {
            @ApiResponse(responseCode = "204", description = "Hostel successfully deleted (No Content)"),
            @ApiResponse(responseCode = "404", description = "Hostel not found with specified ID",
                    content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    })
    public ResponseEntity<Void> deleteHostel(@PathVariable Long id) {
        hostelService.deleteHostel(id);
        return ResponseEntity.noContent().build();
    }
}
