import axios from 'axios';

// Configurable API Base URL (reads from VITE_API_BASE_URL environment variable)
const API_BASE_URL = import.meta.env.VITE_API_BASE_URL || 'http://localhost:8081/api/hostels';

/**
 * REST API client for Hostel operations
 */
export const hostelService = {
  /**
   * Fetch all hostels
   * GET /api/hostels
   */
  async getAllHostels() {
    try {
      const response = await axios.get(API_BASE_URL);
      return response.data;
    } catch (error) {
      throw formatError(error);
    }
  },

  /**
   * Fetch a single hostel by ID
   * GET /api/hostels/{id}
   */
  async getHostelById(id) {
    try {
      const response = await axios.get(`${API_BASE_URL}/${id}`);
      return response.data;
    } catch (error) {
      throw formatError(error);
    }
  },

  /**
   * Create a new hostel record
   * POST /api/hostels
   * Note: The ID is NEVER sent by the frontend; it is generated by the backend.
   */
  async createHostel(hostelData) {
    try {
      // Ensure payload contains only the required business fields
      const payload = {
        hostelName: hostelData.hostelName?.trim(),
        location: hostelData.location?.trim(),
        roomCount: parseInt(hostelData.roomCount, 10),
        wardenName: hostelData.wardenName?.trim(),
      };
      const response = await axios.post(API_BASE_URL, payload);
      return response.data;
    } catch (error) {
      throw formatError(error);
    }
  },

  /**
   * Delete a hostel by ID
   * DELETE /api/hostels/{id}
   */
  async deleteHostel(id) {
    try {
      const response = await axios.delete(`${API_BASE_URL}/${id}`);
      return response.data;
    } catch (error) {
      throw formatError(error);
    }
  },
};

/**
 * Standardize error responses from Axios or backend
 */
function formatError(error) {
  if (error.response) {
    // The server responded with a status code outside the 2xx range
    const data = error.response.data;
    const status = error.response.status;

    // Handle Spring Boot Bean Validation error responses (Map or list of field errors)
    if (data && typeof data === 'object') {
      if (data.errors && Array.isArray(data.errors)) {
        return new Error(data.errors.join(', '));
      }
      if (data.fieldErrors) {
        const details = Object.entries(data.fieldErrors)
          .map(([field, msg]) => `${field}: ${msg}`)
          .join(', ');
        return new Error(details);
      }
      if (data.message) {
        return new Error(data.message);
      }
    }

    if (status === 404) {
      return new Error(`Hostel not found (Status 404).`);
    }
    if (status === 400) {
      return new Error(`Invalid request data (Status 400). Please check your inputs.`);
    }
    return new Error(`Server error (${status}): ${error.response.statusText || 'Unknown error'}`);
  } else if (error.request) {
    // The request was made but no response was received (e.g. backend server is down)
    return new Error(
      `Cannot connect to backend server at ${API_BASE_URL}. Please ensure the Spring Boot server is running on port 8080.`
    );
  } else {
    // Something happened setting up the request
    return new Error(error.message || 'An unexpected error occurred.');
  }
}

export default hostelService;
